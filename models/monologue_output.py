# hari/models/monologue_output.py
"""
Phase 5: Pure sensory monologue output – no command flags.
The LLM becomes a sensory organ, reporting perceptions.
"""

from typing import List, Optional, Literal
from pydantic import BaseModel, Field, field_validator


class InternalCandidate(BaseModel):
    """A single internal cognitive candidate produced by the monologue."""
    content: str
    origin: str = "perception"
    urgency: float = Field(default=0.3, ge=0.0, le=1.0)
    persistence: float = Field(default=0.0, ge=0.0, le=1.0)
    intrinsic_relevance: float = Field(default=0.0, ge=0.0, le=1.0)
    activation_reason: Optional[str] = None


class CandidateArtifact(BaseModel):
    """A candidate for workspace entry, generated by monologue."""
    content: str
    item_type: Literal["memory", "hypothesis", "curiosity_node", "narrative_thread", "open_thought", "self_belief_update"]
    source: str = "monologue"
    urgency: float = Field(default=0.5, ge=0.0, le=1.0)


class MonologueOutput(BaseModel):
    """Pure sensory report describing what became cognitively active."""

    @field_validator("internal_candidates", mode="before")
    @classmethod
    def coerce_string_candidates(cls, v):
        if v is None:
            return []
        if not isinstance(v, list):
            return v
        out = []
        for item in v:
            if isinstance(item, str):
                out.append({"content": item})
            else:
                out.append(item)
        return out

    @field_validator("observations", "questions", "ambiguities", mode="before")
    @classmethod
    def coerce_to_list(cls, v):
        if v is None:
            return []
        if isinstance(v, str):
            return [v]
        return v

    @field_validator("trajectory_deviation", mode="before")
    @classmethod
    def coerce_to_float(cls, v):
        if v is None:
            return 0.0
        if isinstance(v, str):
            try:
                return float(v)
            except (ValueError, TypeError):
                return 0.0
        return v

    observations: List[str] = Field(default_factory=list)
    questions: List[str] = Field(default_factory=list)
    ambiguities: List[str] = Field(default_factory=list)
    internal_candidates: List[InternalCandidate] = Field(default_factory=list)
    curiosity_trigger: Optional[str] = None
    trajectory_deviation: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="0.0 = continuing current thread, 1.0 = complete departure",
    )

    def has_substantive_changes(self) -> bool:
        return (
            bool(self.observations)
            or bool(self.questions)
            or bool(self.ambiguities)
            or bool(self.internal_candidates)
            or self.curiosity_trigger is not None
        )
